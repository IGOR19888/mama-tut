// детерминированный псевдослучай (стабильный вывод)
let seed = 12345;
const rnd = () => (seed = (seed * 1103515245 + 12345) & 0x7fffffff) / 0x7fffffff;
const pick = (arr) => arr[Math.floor(rnd() * arr.length)];
const daysAgo = (n) => new Date(Date.now() - n * 864e5).toISOString();

function genReviews(p) {
  const n = 2 + Math.floor(rnd() * 3); // 2–4 отзыва
  const pool = p.brand === "Mepsi" ? bodyMepsi : bodyLulu;
  const out = [];
  for (let i = 0; i < n; i++) {
    const rating = rnd() < 0.75 ? 5 : 4;
    out.push({
      author: pick(authors),
      rating,
      text: pick(pool),
      pros: pick(prosPool),
      cons: rating === 5 ? "" : pick(consPool),
      photos: [],
      published_at: daysAgo(3 + Math.floor(rnd() * 40)),
    });
  }
  return out;
}

// --- заворачиваем в форму Ozon /v3/product/info ---
function toOzon(p, idx) {
  const specs = p.specs || [];
  return {
    offer_id: p.id,
    sku: 1000000 + idx,
    name: p.title,
    price: String(p.price),
    old_price: p.old ? String(p.old) : "",
    currency_code: "RUB",
    primary_image: p.em,
    images: (p.gallery && p.gallery.length ? p.gallery : [p.em]),
    description: p.desc || p.sub || "",
    marketing_price: p.old ? String(p.price) : "",
    attributes: [
      { name: "Бренд", value: p.brand },
      { name: "Тип", value: p.cat },
      ...(p.sub ? [{ name: "Краткое описание", value: p.sub }] : []),
      ...specs.map(([k, v]) => ({ name: k, value: v })),
    ],
    badge: p.badge || "",
    rating: p.rate,
    reviews_count: p.rev || 0,
    stocks: { present: p.stock || 50, reserved: 0 },
    seller: p.seller || "",
    reviews: genReviews(p),
  };
}

